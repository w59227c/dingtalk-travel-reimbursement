async def local(repeats):
    from app.services.ocr_service import OcrService, parsed_expense_payload
    from app.services.process_jobs import KillableProcessRunner
    from app.services.temp_files import StoredFile
    from app.services.warm_ocr_process import WarmOcrProcess

    os.environ["PADDLE_PDX_DISABLE_MODEL_SOURCE_CHECK"] = "1"
    warm = WarmOcrProcess()
    config = settings()
    runner = KillableProcessRunner(
        warm,
        admission_timeout_seconds=config.ocr_queue_wait_seconds,
        max_waiters=config.ocr_queue_max_waiters,
    )
    service = OcrService(config, None, runner)
    result = {
        "mode": "local",
        "platform": platform.platform(),
        "repeats": repeats,
        "utc": datetime.now(UTC).isoformat(),
        "rows": [],
    }
    try:
        # Round-major ordering exposes initial cold startup separately.
        for repeat in range(repeats):
            for item in samples():
                path = OUT / item["file"]
                extension = path.suffix.removeprefix(".")
                stored = StoredFile(
                    "synthetic",
                    path,
                    extension,
                    "application/pdf" if extension == "pdf" else "image/png",
                    path.stat().st_size,
                    path.name,
                )
                started = time.perf_counter()
                row = {"file": path.name, "repeat": repeat, "fixture_sha256": item["sha256"]}
                try:
                    if item["kind"] == "itinerary":
                        parsed = await service.recognize_itinerary_file(stored, reference_year=2026)
                        if parsed["status"] != "recognized":
                            raise RuntimeError(parsed.get("error", {}).get("code", "FAILED"))
                        actual = {
                            **parsed["summary"],
                            "trips": len(parsed["trips"]),
                            "complete": parsed["complete"],
                            "warnings": parsed["warnings"],
                        }
                    else:
                        parsed = await service.recognize_file(stored, reference_year=2026)
                        actual = parsed_expense_payload("synthetic", parsed)
                    row.update(status="ok", actual=actual, **metrics(item["expected"], actual))
                except Exception as exc:
                    row.update(
                        status="error", error=type(exc).__name__, code=getattr(exc, "code", None)
                    )
                row["seconds"] = round(time.perf_counter() - started, 4)
                result["rows"].append(row)
                save("local.json", result)
                print(json.dumps({k: v for k, v in row.items() if k != "actual"}), flush=True)
    finally:
        await runner.close()
        await warm.close()
    result["parent_peak_rss_bytes"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    result["child_peak_rss_bytes"] = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
    save("local.json", result)


def block_text(content):
    """Minimal documented adapter: preserve table columns, discard only markup."""
    text = re.sub(r"</t[dh]>", "    ", content, flags=re.I)
    text = re.sub(r"</tr>|</p>|<br\s*/?>", "\n", text, flags=re.I)
    text = re.sub(r"<[^>]+>", "", text)
    text = html.unescape(text)
    text = re.sub(r"^\s{0,3}#{1,6}\s+", "", text, flags=re.M)
    text = text.replace("**", "")
    return "\n".join(
        line.replace("|", "    ").strip()
        for line in text.splitlines()
        if line.strip() and not re.fullmatch(r"[| :\-]+", line)
    )


def remote(endpoint, limit):
    import httpx

    from app.ocr.itinerary import ItineraryPage, parse_itinerary_pages
    from app.ocr.parsers import ReceiptParserRegistry
    from app.ocr.types import OcrLine, ParseContext
    from app.services.ocr_service import parsed_expense_payload, parsed_itinerary_payload

    allowed_endpoints = {
        "https://free-oxr.somark.ai/api/v1/parse/sync",
        "https://free-oxr.somark.cn/api/v1/parse/sync",
    }
    if endpoint not in allowed_endpoints:
        raise ValueError("Only public OXR synthetic-test endpoints are allowed")
    filename = "remote-cn.json" if ".cn/" in endpoint else "remote.json"
    result = {
        "mode": "official_free_api",
        "endpoint": endpoint,
        "utc": datetime.now(UTC).isoformat(),
        "rows": [],
    }
    if (OUT / filename).exists():
        result = json.loads((OUT / filename).read_text())
    items = samples()
    hashes = {item["file"]: item["sha256"] for item in items}
    result["rows"] = [
        row for row in result["rows"] if row.get("fixture_sha256") == hashes.get(row["file"])
    ]
    completed = {row["file"] for row in result["rows"]}
    with httpx.Client(timeout=httpx.Timeout(120, connect=20), trust_env=False) as client:
        for item in items[:limit]:
            if item["file"] in completed:
                continue
            path = OUT / item["file"]
            started = time.perf_counter()
            row = {"file": path.name, "fixture_sha256": item["sha256"]}
            try:
                with path.open("rb") as handle:
                    response = client.post(
                        endpoint,
                        data={
                            "api_key": "dummy",
                            "output_formats": ["json", "markdown"],
                            "feature_config": json.dumps({"keep_header_footer": True}),
                            "element_formats": json.dumps({"table": "html", "image": "none"}),
                        },
                        files={"file": (path.name, handle)},
                    )
                row["http_status"] = response.status_code
                response.raise_for_status()
                body = response.json()
                row["api_code"] = body.get("code")
                if body.get("code") != 0 or body.get("data", {}).get("error"):
                    row.update(status="api_error")
                else:
                    outputs = body["data"]["result"]["outputs"]
                    pages = outputs.get("json", {}).get("pages", [])
                    if not pages:
                        raise ValueError("No structured page output")
                    texts = [
                        "\n".join(
                            block_text(block.get("content", "")) for block in page.get("blocks", [])
                        )
                        for page in pages
                    ]
                    # Presence checks separate recognition from downstream Parser errors.
                    row["numeric_evidence_present"] = {
                        key: str(value) in "\n".join(texts)
                        for key, value in item["expected"].items()
                        if key in {"amount", "originalAmount"} and value is not None
                    }
                    lines = [
                        [OcrLine(line, 1.0) for line in text.splitlines() if line.strip()]
                        for text in texts
                    ]
                    # 1.0 is an adapter placeholder, NOT measured OXR confidence.
                    if item["kind"] == "itinerary":
                        parsed = parse_itinerary_pages(
                            [
                                ItineraryPage(index, tuple(page_lines), text, "paddle")
                                for index, (text, page_lines) in enumerate(
                                    zip(texts, lines, strict=True), 1
                                )
                            ],
                            page_count=len(pages),
                            reference_year=2026,
                        )
                        payload = parsed_itinerary_payload("synthetic", parsed)
                        actual = {
                            **payload["summary"],
                            "trips": len(payload["trips"]),
                            "complete": payload["complete"],
                            "warnings": payload["warnings"],
                        }
                    else:
                        parsed = ReceiptParserRegistry().parse(
                            [line for page_lines in lines for line in page_lines],
                            ParseContext(2026),
                        )
                        actual = parsed_expense_payload("synthetic", parsed)
                    row.update(status="ok", actual=actual, **metrics(item["expected"], actual))
            except Exception as exc:
                row.update(status="error", error=type(exc).__name__)
            row["seconds"] = round(time.perf_counter() - started, 4)
            result["rows"].append(row)
            # Never persist raw OCR, remote URLs or server task identifiers.
            save(filename, result)
            print(json.dumps({k: v for k, v in row.items() if k != "actual"}), flush=True)


def summarize():
    by_file = {item["file"]: item for item in samples()}
    for filename in ("local.json", "remote.json", "remote-cn.json"):
        if not (OUT / filename).exists():
            continue
        result = json.loads((OUT / filename).read_text())
        rows = result["rows"]
        for row in rows:
            if row["status"] == "ok":
                row.update(metrics(by_file[row["file"]]["expected"], row["actual"]))
        save(filename, result)
        ok = [row for row in rows if row["status"] == "ok"]
        print(
            filename,
            json.dumps(
                {
                    "attempts": len(rows),
                    "successes": len(ok),
                    "all_fields_correct": sum(row["all_correct"] for row in ok),
                    "fields_correct": sum(row["correct"] for row in ok),
                    "fields_scored_on_success": sum(row["total"] for row in ok),
                    "median_seconds_all_attempts": statistics.median(
                        row["seconds"] for row in rows
                    ),
                }
            ),
        )


