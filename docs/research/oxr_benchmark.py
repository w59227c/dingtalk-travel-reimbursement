def save(name, data):
    (OUT / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def generate():
    from PIL import Image, ImageDraw, ImageFilter, ImageFont
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.pdfgen import canvas

    OUT.mkdir(parents=True, exist_ok=True)
    pdfmetrics.registerFont(
        TTFont("FixtureCJK", "/System/Library/Fonts/Supplemental/Arial Unicode.ttf")
    )
    font = ImageFont.truetype("/System/Library/Fonts/STHeiti Light.ttc", 32)
    samples = []
    for case in CASES:
        image = Image.new("RGB", (1500, 900), "white")
        draw = ImageDraw.Draw(image)
        draw.rectangle((30, 30, 1470, 870), outline="#777777", width=2)
        for index, line in enumerate(case["lines"]):
            draw.text((70, 90 + index * 85), line, font=font, fill="black")
        for fmt in case["formats"]:
            path = OUT / f"{case['id']}.{fmt}"
            if fmt == "pdf":
                pdf = canvas.Canvas(str(path), pagesize=(750, 450))
                pdf.setFont("FixtureCJK", 16)
                for index, line in enumerate(case["lines"]):
                    pdf.drawString(35, 390 - index * 42.5, line)
                pdf.save()
            elif fmt == "scan.pdf":
                image.save(path, "PDF", resolution=144)
            elif fmt == "degraded.png":
                small = image.resize((750, 450)).resize(image.size)
                small.filter(ImageFilter.GaussianBlur(0.65)).rotate(
                    2, expand=True, fillcolor="white"
                ).save(path)
            else:
                image.save(path)
            samples.append(
                {
                    "file": path.name,
                    "case": case["id"],
                    "kind": case.get("kind", "receipt"),
                    "expected": case["expected"],
                    "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                }
            )
    save("samples.json", samples)
    print(f"Generated {len(samples)} synthetic samples in {OUT}", flush=True)


def samples():
    items = json.loads((OUT / "samples.json").read_text())
    allowed = {f"{case['id']}.{fmt}" for case in CASES for fmt in case["formats"]}
    if {item["file"] for item in items} != allowed:
        raise ValueError("Synthetic fixture allowlist mismatch")
    # Revalidate before any upload; this utility never accepts arbitrary input paths.
    for item in items:
        path = OUT / item["file"]
        if path.is_symlink() or hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]:
            raise ValueError("Synthetic fixture changed")
        item["expected"] = next(case["expected"] for case in CASES if case["id"] == item["case"])
    return items


def metrics(expected, actual):
    checks = {key: actual.get(key) == value for key, value in expected.items()}
    return {
        "correct": sum(checks.values()),
        "total": len(checks),
        "all_correct": all(checks.values()),
        "checks": checks,
    }


