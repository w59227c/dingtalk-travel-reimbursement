    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["generate", "local", "remote", "summary"])
    parser.add_argument("--repeats", type=int, default=2)
    parser.add_argument("--limit", type=int, default=12)
    parser.add_argument("--endpoint", default="https://free-oxr.somark.ai/api/v1/parse/sync")
    args = parser.parse_args()
    if args.mode == "generate":
        generate()
    elif args.mode == "local":
        asyncio.run(local(args.repeats))
    elif args.mode == "remote":
        remote(args.endpoint, args.limit)
    else:
        summarize()
